import Foundation
import AppKit

/// Polls `NSPasteboard.general.changeCount` and records clipboard history.
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    /// Custom type written when we put history items back on the pasteboard.
    static let selfWriteType = "io.github.bianyanhui.HisCopy.selfWrite"

    /// Standard nspasteboard markers (ignore when present).
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private var timer: Timer?
    private var lastChangeCount: Int = -1
    private var ignoreNextChange = false
    private let pollInterval: TimeInterval = 0.35

    private init() {}

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor in
                self?.poll()
            }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call before writing to the pasteboard from HisCopy itself.
    func markNextWriteAsSelf() {
        ignoreNextChange = true
    }

    private func poll() {
        let store = ClipboardHistoryStore.shared
        guard !store.isPaused else { return }

        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if ignoreNextChange {
            ignoreNextChange = false
            return
        }

        // Ignore our own write-back marker.
        if pb.types?.contains(NSPasteboard.PasteboardType(Self.selfWriteType)) == true {
            return
        }

        // Ignore concealed / transient / auto-generated content when present.
        if let types = pb.types {
            if types.contains(Self.concealedType)
                || types.contains(Self.transientType)
                || types.contains(Self.autoGeneratedType) {
                return
            }
        }

        if let item = capture(from: pb) {
            store.add(item)
        }
    }

    private func capture(from pb: NSPasteboard) -> ClipboardItem? {
        let types = pb.types ?? []

        // File URLs
        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [
               .urlReadingFileURLsOnly: true
           ]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            let preview: String
            if paths.count == 1 {
                preview = (paths[0] as NSString).lastPathComponent
            } else {
                preview = "\(paths.count) 个文件"
            }
            return ClipboardItem(
                kind: .files,
                textPreview: String(preview.prefix(200)),
                fileURLs: paths
            )
        }

        // Image (TIFF / PNG)
        if types.contains(.tiff) || types.contains(.png) {
            var imageData: Data?
            if let png = pb.data(forType: .png) {
                imageData = png
            } else if let tiff = pb.data(forType: .tiff),
                      let image = NSImage(data: tiff),
                      let tiffRep = image.tiffRepresentation,
                      let rep = NSBitmapImageRep(data: tiffRep),
                      let png = rep.representation(using: .png, properties: [:]) {
                imageData = png
            }
            if let data = imageData {
                let id = UUID()
                if let name = ClipboardHistoryStore.shared.saveImageData(data, id: id) {
                    let sizeKB = max(1, data.count / 1024)
                    return ClipboardItem(
                        id: id,
                        kind: .image,
                        textPreview: "图片 (\(sizeKB) KB)",
                        imageFileName: name
                    )
                }
            }
        }

        // HTML (optional) + plain text
        let html = pb.string(forType: .html)
        let plain = pb.string(forType: .string)
        let rtf = pb.data(forType: .rtf)

        if let html, !html.isEmpty {
            let preview = (plain?.trimmingCharacters(in: .whitespacesAndNewlines)).flatMap { $0.isEmpty ? nil : $0 }
                ?? html.replacingOccurrences(of: "<[^>]+>", with: "", options: .regularExpression)
                    .trimmingCharacters(in: .whitespacesAndNewlines)
            guard !preview.isEmpty || !(plain ?? "").isEmpty else { return nil }
            return ClipboardItem(
                kind: .html,
                textPreview: String((preview.isEmpty ? (plain ?? "HTML") : preview).prefix(200)),
                plainText: plain,
                html: html
            )
        }

        if let rtf, !rtf.isEmpty {
            let preview = plain?.trimmingCharacters(in: .whitespacesAndNewlines) ?? "RTF"
            guard !preview.isEmpty || plain != nil else { return nil }
            return ClipboardItem(
                kind: .rtf,
                textPreview: String((preview.isEmpty ? "RTF" : preview).prefix(200)),
                plainText: plain,
                rtfData: rtf
            )
        }

        if let plain {
            let trimmed = plain.trimmingCharacters(in: .whitespacesAndNewlines)
            // Allow whitespace-only if original had content; skip empty.
            guard !plain.isEmpty else { return nil }
            let preview = trimmed.isEmpty ? "(空白文本)" : trimmed
            return ClipboardItem(
                kind: .text,
                textPreview: String(preview.prefix(200)),
                plainText: plain
            )
        }

        return nil
    }
}
